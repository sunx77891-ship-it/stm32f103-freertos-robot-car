static uint8_t OLED_Buffer[OLED_WIDTH * OLED_PAGES];

/* -------- 底层 I2C 发送 -------- */

/* 向 SSD1306 发送命令字节 */
static void OLED_WriteCmd(uint8_t cmd)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(OLED_WRITE);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(0x00);     /* 控制字节：0x00 = 后续是命令 */
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(cmd);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

/* 向 SSD1306 发送数据字节 */
static void OLED_WriteData(uint8_t data)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(OLED_WRITE);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(0x40);     /* 控制字节：0x40 = 后续是数据 */
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(data);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

/* -------- 公开 API -------- */

/* SSD1306 初始化序列 */
void OLED_Init(void)
{
    OLED_I2C_GPIO_Init();

    /* 关闭显示 */
    OLED_WriteCmd(0xAE);

    /* 时钟分频 & 振荡频率 */
    OLED_WriteCmd(0xD5);
    OLED_WriteCmd(0x80);  /* 默认值 */

    /* 多路复用比 */
    OLED_WriteCmd(0xA8);
    OLED_WriteCmd(0x3F);  /* 64 行 */

    /* 显示偏移 */
    OLED_WriteCmd(0xD3);
    OLED_WriteCmd(0x00);

    /* 显示起始行 */
    OLED_WriteCmd(0x40);

    /* 段重映射：0xA0=正常(列0→seg0)  0xA1=左右镜像(列0→seg127)
       本机屏幕物理正向安装，用 0xA0 不做硬件翻转，字模本身即正向 */
    OLED_WriteCmd(0xA1);

    /* COM 扫描方向：0xC0=正常  0xC8=上下翻转（配合0xA0保持正向） */
    OLED_WriteCmd(0xC8);

    /* COM 引脚硬件配置 */
    OLED_WriteCmd(0xDA);
    OLED_WriteCmd(0x12);

    /* 对比度 */
    OLED_WriteCmd(0x81);
    OLED_WriteCmd(0xCF);

    /* 预充电周期 */
    OLED_WriteCmd(0xD9);
    OLED_WriteCmd(0xF1);

    /* VCOMH 电压 */
    OLED_WriteCmd(0xDB);
    OLED_WriteCmd(0x40);

    /* 全屏点亮关闭 */
    OLED_WriteCmd(0xA4);

    /* 正常显示（非反色） */
    OLED_WriteCmd(0xA6);

    /* 禁用滚动 */
    OLED_WriteCmd(0x2E);

    /* 电荷泵开启 */
    OLED_WriteCmd(0x8D);
    OLED_WriteCmd(0x14);

    /* 开启显示 */
    OLED_WriteCmd(0xAF);

    OLED_Clear();
    OLED_Refresh();
}

/* 清空帧缓冲 */
void OLED_Clear(void)
{
    memset(OLED_Buffer, 0x00, sizeof(OLED_Buffer));
}

/* 全屏刷新 — 将帧缓冲写入 SSD1306 GDDRAM
   注意: 只用单字节命令(0xB0/0x00/0x10), 不用 0x21/0x22 多字节命令
   因为 OLED_WriteCmd 每次是独立 I2C 事务, 多字节命令的参数会丢失导致状态机混乱 */
void OLED_Refresh(void)
{
    uint8_t page, col;

    for (page = 0; page < OLED_PAGES; page++) {
        /* 设置页地址 (0xB0~0xB7, 单字节命令) */
        OLED_WriteCmd(0xB0 + page);
        /* 设置列起始地址低 4 位 = 0 (0x00, 单字节命令) */
        OLED_WriteCmd(0x00);
        /* 设置列起始地址高 4 位 = 0 (0x10, 单字节命令) */
        OLED_WriteCmd(0x10);

        /* 连续写入当前页的 128 列数据, 列地址自动递增 0->127 */
        OLED_I2C_Start();
        OLED_I2C_WriteByte(OLED_WRITE);
        OLED_I2C_WaitAck();
        OLED_I2C_WriteByte(0x40);   /* 控制字节 0x40 = 后续是数据 */
        OLED_I2C_WaitAck();
        for (col = 0; col < OLED_WIDTH; col++) {
            OLED_I2C_WriteByte(OLED_Buffer[page * OLED_WIDTH + col]);
            OLED_I2C_WaitAck();
        }
        OLED_I2C_Stop();
    }
}

/* 在帧缓冲中画点 — color: 1=亮（白），0=灭（黑） */
void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t color)
{
    uint8_t page;

    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;

    page = y / 8;
    if (color)
        OLED_Buffer[page * OLED_WIDTH + x] |=  (1 << (y % 8));
    else
        OLED_Buffer[page * OLED_WIDTH + x] &= ~(1 << (y % 8));
}

/* -------- 8x16 大字体渲染 ---------- */

void OLED_ShowChar16(uint8_t x, uint8_t y, char ch)
{
    uint8_t row, col;

    if (x + 8 > OLED_WIDTH || y + 16 > OLED_HEIGHT) return;
    if (ch < 0x20 || ch > 0x7E) ch = ' ';

    for (row = 0; row < 16; row++) {
        uint8_t data = Font8x16[(ch - 0x20) * 16 + row];
        for (col = 0; col < 8; col++) {
            if (data & (0x80 >> col))
                OLED_DrawPixel(x + col, y + row, 1);
            else
                OLED_DrawPixel(x + col, y + row, 0);
        }
    }
}

void OLED_ShowString16(uint8_t x, uint8_t y, const char *str)
{
    uint8_t cx = x;

    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 16;
            if (y + 16 > OLED_HEIGHT) return;
        } else {
            OLED_ShowChar16(cx, y, *str);
            cx += 8;
            if (cx + 8 > OLED_WIDTH) {
                cx = x;
                y += 16;
                if (y + 16 > OLED_HEIGHT) return;
            }
        }
        str++;
    }
}
