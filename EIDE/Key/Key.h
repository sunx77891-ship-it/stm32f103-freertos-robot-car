#ifndef KEY_H
#define KEY_H

#include <stdint.h>

/* 按键 ID */
typedef enum {
    KEY_K1 = 0,   /* PC13 */
    KEY_K2,       /* PC14 */
    KEY_K3,       /* PC0  */
    KEY_K4,       /* PC1  */
    KEY_K5,       /* PC2  */
    KEY_K6,       /* PC3  */
    KEY_NUM
} Key_ID_t;

/**************************************************************************
函数名：Key_Init
函数功能：初始化按键状态机
**************************************************************************/
void Key_Init(void);

/**************************************************************************
函数名：Key_Process
函数功能：按键状态机处理，每 10ms 调用一次
         按下消抖 → 保持计时 → 松开判定短按/长按
**************************************************************************/
void Key_Process(void);

/**************************************************************************
函数名：Key_GetPress
函数功能：读取并清除指定按键的消抖确认按下事件
入口参数：key - 按键 ID
返回值：1=有按下事件，0=无事件
**************************************************************************/
uint8_t Key_GetPress(Key_ID_t key);

/**************************************************************************
函数名：Key_GetShortPress / Key_GetLongPress
函数功能：读取并清除按键事件标志
入口参数：key - 按键 ID
返回值  ：1=有事件  0=无事件
**************************************************************************/
uint8_t Key_GetShortPress(Key_ID_t key);
uint8_t Key_GetLongPress(Key_ID_t key);

#endif /* KEY_H */
